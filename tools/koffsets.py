import os
import subprocess
import sys

from clang.cindex import CursorKind, Diagnostic, Index

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

CLANG_ARGS = [
    "-target", "x86_64-unknown-none-elf", # same as $(CC)
    "-ffreestanding",
    "-resource-dir", subprocess.check_output(["clang", "-print-resource-dir"], text=True).strip(),
    f"-I{BASE_DIR}",
    f"-I{BASE_DIR}/include",
    f"-I{BASE_DIR}/arch/x86_64/include",
]


def get_offsets(header_path, struct_name):
    index = Index.create()
    tu = index.parse(header_path, args=CLANG_ARGS)

    for diag in tu.diagnostics:
        if diag.severity >= Diagnostic.Error:
            raise RuntimeError(f"{header_path}: {diag}")

    try:
        struct_cursor = None

        cursor = tu.cursor
        if cursor is None:
            raise RuntimeError(f"failed to parse translation unit from {header_path}")

        for node in cursor.walk_preorder():
            if node.kind == CursorKind.STRUCT_DECL and node.spelling == struct_name:
                if node.is_definition():
                    struct_cursor = node
                    break

        if struct_cursor is None:
            raise KeyError(struct_name)

        offsets = []

        for field in struct_cursor.get_children():
            if field.kind != CursorKind.FIELD_DECL:
                continue

            offsets.append((field.spelling, field.get_field_offsetof() // 8))

        return offsets

    except KeyError as exc:
        raise RuntimeError(f"struct name {struct_name} was not found in {header_path}") from exc


def get_all_offsets(header_path, struct_names):
    all_offsets = {}

    for struct_name in struct_names:
        all_offsets[struct_name] = get_offsets(header_path, struct_name)

    return all_offsets


def generate_c(entries):
    out = []

    out.append("/* generated by tools/koffsets.py */")
    out.append("")
    out.append("#pragma once")
    out.append("")

    macro_entries = []
    for _, struct_name, offsets in entries:
        for field, offset in offsets:
            macro_name = f"{struct_name.upper()}_{field.upper()}_OFFSET"
            macro_entries.append((macro_name, offset))

    max_len = max((len(name) for name, _ in macro_entries), default=0)

    for name, offset in macro_entries:
        out.append(f"#define {name:<{max_len+1}} 0x{offset:05x}")

    out.append("")

    return "\n".join(out)


def parse_entries(argv):
    output_path = None
    if argv and argv[-1].endswith((".h", ".hpp", ".inc")):
        output_path = argv[-1]
        argv = argv[:-1]

    if not argv:
        return [], output_path

    entries = []
    i = 0
    while i < len(argv):
        token = argv[i]
        if not token.endswith((".h", ".hpp", ".inc")):
            raise ValueError(f"expected header file path, got: {token}")

        header_path = token
        i += 1

        struct_names = []
        while i < len(argv) and not argv[i].endswith((".h", ".hpp", ".inc")):
            struct_names.append(argv[i])
            i += 1

        if not struct_names:
            raise ValueError(f"no struct names provided for {header_path}")

        entries.append((header_path, struct_names))

    return entries, output_path


def main():
    if len(sys.argv) < 3:
        print(f"usage: {sys.argv[0]} <header> [<struct> ...] [output]")
        return 1

    entries, output_path = parse_entries(sys.argv[1:])

    all_entries = []
    total_fields = 0
    for header_path, struct_names in entries:
        for struct_name in struct_names:
            offsets = get_offsets(header_path, struct_name)
            all_entries.append((header_path, struct_name, offsets))
            total_fields += len(offsets)

    if output_path is not None:
        with open(output_path, "w", encoding="UTF-8") as f:
            f.write(generate_c(all_entries))

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
